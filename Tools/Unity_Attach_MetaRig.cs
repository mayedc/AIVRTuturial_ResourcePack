using UnityEditor.SceneManagement;
using AIVRWorkshop.V4;
var basePath="Assets/AI_VR_Workshop_V4/Scenes/";
var scene=UnityEngine.SceneManagement.SceneManager.GetActiveScene();
if(scene.path!=basePath+"Workshop_Desktop.unity")throw new Exception("Expected teaching scene");
EditorSceneManager.SaveScene(scene);
var target=basePath+"Workshop_MetaVR.unity";
if(System.IO.File.Exists(target))throw new Exception("MetaVR scene already exists; preserve it and choose a new filename.");
EditorSceneManager.SaveScene(scene,target);
var drive=Object.FindFirstObjectByType<WorkshopDrive>();
var eye=drive.transform.Find("DriverEyeAnchor");
var prefab=AssetDatabase.LoadAssetAtPath<GameObject>("Packages/com.meta.xr.sdk.core/Prefabs/OVRCameraRig.prefab");
if(prefab==null)throw new Exception("Installed Meta prefab not found");
var go=(GameObject)PrefabUtility.InstantiatePrefab(prefab);go.name="Workshop_OVRCameraRig";
go.transform.SetParent(eye,false);go.transform.localPosition=Vector3.zero;go.transform.localRotation=Quaternion.identity;go.transform.localScale=Vector3.one;
var rig=go.GetComponent<OVRCameraRig>();rig.usePerEyeCameras=false;
var manager=go.GetComponent<OVRManager>();manager.trackingOriginType=OVRManager.TrackingOrigin.EyeLevel;manager.usePositionTracking=true;
var center=go.transform.Find("TrackingSpace/CenterEyeAnchor");if(center==null)throw new Exception("Center eye missing");
var camera=center.GetComponent<Camera>();camera.nearClipPlane=.03f;camera.farClipPlane=250;camera.clearFlags=CameraClearFlags.SolidColor;camera.backgroundColor=new Color(.09f,.14f,.19f);
var desktop=eye.Find("DesktopCamera");desktop.GetComponent<Camera>().enabled=false;desktop.GetComponent<AudioListener>().enabled=false;
var curtain=drive.comfortCurtain;curtain.transform.SetParent(center,false);curtain.transform.localPosition=new Vector3(0,0,.10f);curtain.transform.localRotation=Quaternion.identity;curtain.enabled=false;
Object.FindFirstObjectByType<WorkshopDesktopPanel>().showDesktopControls=true;
EditorUtility.SetDirty(manager);EditorUtility.SetDirty(rig);EditorUtility.SetDirty(drive);PrefabUtility.RecordPrefabInstancePropertyModifications(manager);PrefabUtility.RecordPrefabInstancePropertyModifications(rig);
EditorSceneManager.MarkSceneDirty(scene);EditorSceneManager.SaveScene(scene);AssetDatabase.SaveAssets();
return new {scene=scene.path,eye=eye.position,camera=center.name,tracking=manager.trackingOriginType.ToString(),headsetTested=false};
